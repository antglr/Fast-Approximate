def fig(src, crop=None):
    # copy into FIGS (crop = fractions left, top, right, bottom); reuse the copy if the source is gone
    out = FIGS + os.path.basename(src).replace('.png', '_crop.png' if crop else '.png')
    if os.path.exists(src):
        im = Image.open(src)
        if crop:
            w, h = im.size
            im = im.crop((int(crop[0] * w), int(crop[1] * h), int(crop[2] * w), int(crop[3] * h)))
        im.save(out)
    return out


